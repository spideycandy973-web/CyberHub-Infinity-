#pragma once
#include <cstdint>

namespace neon {

// 5x7 bitmap font. Each glyph is 5 bytes (columns), 7 bits per column (bit 0 = top row).
// Supported characters: 0-9 F P S M . - (space)
struct Glyph {
    uint8_t cols[5];
};

inline Glyph getGlyph(char c) {
    switch (c) {
        case '0': return {{0x3E, 0x51, 0x49, 0x45, 0x3E}};
        case '1': return {{0x00, 0x42, 0x7F, 0x40, 0x00}};
        case '2': return {{0x42, 0x61, 0x51, 0x49, 0x46}};
        case '3': return {{0x21, 0x41, 0x45, 0x4B, 0x31}};
        case '4': return {{0x18, 0x14, 0x12, 0x7F, 0x10}};
        case '5': return {{0x27, 0x45, 0x45, 0x45, 0x39}};
        case '6': return {{0x3C, 0x4A, 0x49, 0x49, 0x30}};
        case '7': return {{0x01, 0x71, 0x09, 0x05, 0x03}};
        case '8': return {{0x36, 0x49, 0x49, 0x49, 0x36}};
        case '9': return {{0x06, 0x49, 0x49, 0x29, 0x1E}};
        case 'F': return {{0x7F, 0x09, 0x09, 0x09, 0x01}};
        case 'P': return {{0x7F, 0x09, 0x09, 0x09, 0x06}};
        case 'S': return {{0x46, 0x49, 0x49, 0x49, 0x31}};
        case 'M': return {{0x7F, 0x02, 0x0C, 0x02, 0x7F}};
        case '.': return {{0x00, 0x60, 0x60, 0x00, 0x00}};
        case '-': return {{0x08, 0x08, 0x08, 0x08, 0x08}};
        default:  return {{0x00, 0x00, 0x00, 0x00, 0x00}};
    }
}

} // namespace neon
